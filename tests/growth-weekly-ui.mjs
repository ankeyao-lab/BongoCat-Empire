test('automatic-cycle toggle changes only its setting; manual wearing stays independent', async () => {
  const page = await openFixture()
  await page.getByRole('switch', { name: '满级后自动循环', exact: true }).click()
  await page.waitForFunction(() => window.__growthUI.snapshot().autoCycle === false)
  await page.locator('.outfit-card').last().click()
  await page.getByRole('button', { name: '穿上这套装扮', exact: true }).click()
  await page.getByRole('button', { name: '正在穿戴这套装扮', exact: true }).waitFor()
  assert.deepEqual(await page.evaluate(() => window.__growthUI.calls), [
    { name: 'updateSettings', args: [{ autoCycle: false }] },
    { name: 'equip', args: [9, 'wizard'] },
  ])
  assert.equal(await page.evaluate(() => window.__growthUI.snapshot().roundLevel), 2)
  assert.equal(await page.evaluate(() => window.__growthUI.snapshot().growthThemeId), 'wizard')
  await page.close()
})

