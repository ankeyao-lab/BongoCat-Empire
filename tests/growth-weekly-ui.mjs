test('weekly controls remain within a narrow 390-pixel layout', async () => {
  const page = await openFixture(390)
  const horizontalOverflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  assert.ok(horizontalOverflow <= 1, `Unexpected horizontal overflow ${horizontalOverflow}`)
  for (const selector of ['#weekly-daily-budget', '#weekly-active-days', '.weekly-theme-mode button', '.cycle-setting button']) {
    const box = await page.locator(selector).boundingBox()
    assert.ok(box && box.x >= 0 && box.x + box.width <= 390, selector)
  }
  await page.locator('.weekly-section').screenshot({ path: fileURLToPath(new URL('weekly-390.png', outputDirectory)) })
  await page.close()
})
