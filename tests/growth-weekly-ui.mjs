function fixtureModule(vueURL) {
  return `
import { ref, computed } from ${JSON.stringify(vueURL)};
import { growthThemeIds, levelAtPresses } from '/src/data/wizard-theme.ts';
const percentages = [0, 3, 10, 20, 35, 50, 65, 82, 100];
const thresholds = percentages.map(p => 25000 * p / 100);
const themes = Object.fromEntries(growthThemeIds.map(id => [id, {
  presses: id === 'wizard' ? 50000 : 0, thresholds: [...thresholds],
  unlockedLevel: id === 'wizard' ? 9 : 1, equippedLevel: id === 'wizard' ? 2 : 1,
  thresholdMode: 'weekly', roundPresses: id === 'wizard' ? 1000 : 0,
  roundLevel: id === 'wizard' ? 2 : 1
}]));
function aliases(s) {
  const t = s.themes[s.growthThemeId];
  return { ...s, thresholds: t.thresholds, themePresses: t.presses,
    level: t.unlockedLevel, equippedLevel: t.equippedLevel,
    roundPresses: t.roundPresses, roundLevel: t.roundLevel,
    unlockedLevels: Array.from({length:t.unlockedLevel}, (_,i)=>i+1) };
}
const state = ref(aliases({ schemaVersion:4, ruleVersion:1, totalPresses:50000,
  growthThemeId:'wizard', outfitThemeId:'wizard', themes,
  dailyPressBudget:5000, activeDaysPerWeek:5, weeklyTargetPresses:25000,
  autoCycle:true, cycleRound:2, paused:false, autoEquip:true,
  reducedMotion:true, showProgress:true, quietMode:false, decorationsEnabled:true,
  listening:false, lastSavedAt:null
}));
const pending=ref(false), error=ref(null), calls=[];
let failure='';
const patch = value => { state.value=aliases({...state.value,...value}); };
const patchTheme = (id,value) => patch({themes:{...state.value.themes,[id]:{...state.value.themes[id],...value}}});
async function command(name,args,action) {
  calls.push({name,args}); pending.value=true;
  try { await new Promise(resolve=>setTimeout(resolve,20)); if(failure){const message=failure;failure='';throw new Error(message);} action?.(); }
  finally { pending.value=false; }
}
window.__growthUI={
  calls, patch, patchTheme,
  failNext(message){failure=message},
  snapshot(){return JSON.parse(JSON.stringify(state.value))}
};
export function useGrowth(){return {
  state, initialized:ref(true), error, busy:computed(()=>pending.value), isDemo:true,
  clearError(){error.value=null}, refresh:async()=>{},
  setWeeklyPlan:(daily,days)=>command('setWeeklyPlan',[daily,days],()=>{
    const next = Object.fromEntries(Object.entries(state.value.themes).map(([id,t])=>[id,
      t.thresholdMode==='custom' ? t : {...t,thresholds:percentages.map(p=>daily*days*p/100)}]));
    patch({dailyPressBudget:daily,activeDaysPerWeek:days,weeklyTargetPresses:daily*days,themes:next});
  }),
  useWeeklyThresholds:id=>command('useWeeklyThresholds',[id],()=>patchTheme(id,{thresholdMode:'weekly',thresholds:percentages.map(p=>state.value.weeklyTargetPresses*p/100)})),
  setThresholds:(id,values)=>command('setThresholds',[id,values],()=>patchTheme(id,{thresholdMode:'custom',thresholds:values})),
  updateSettings:settings=>command('updateSettings',[settings],()=>patch(settings)),
  setOutfitTheme:id=>command('setOutfitTheme',[id],()=>patch({outfitThemeId:id})),
  setGrowthTheme:id=>command('setGrowthTheme',[id],()=>patch({growthThemeId:id})),
  equip:(level,id)=>command('equip',[level,id],()=>{
    patchTheme(id,{equippedLevel:level});patch({outfitThemeId:id});
  }),
  setDemoPresses:value=>command('setDemoPresses',[value],()=>patchTheme(state.value.growthThemeId,{roundPresses:value,roundLevel:levelAtPresses(value,state.value.thresholds)})),
  exportBackup:async()=>'', importBackup:async()=>{}, reset:async()=>{}
};}
`
}

async function openFixture(width = 1100) {
  const page = await browser.newPage({ viewport: { width, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/src/composables/useGrowth.ts*', async (route) => {
    const original = await route.fetch()
    const source = await original.text()
    const vueURL = source.match(/from\s+["']([^"']*\/vue\.js[^"']*)["']/)?.[1]
    assert.ok(vueURL, 'Find the actual Vue import generated by Vite')
    await route.fulfill({ status: 200, contentType: 'application/javascript', body: fixtureModule(vueURL) })
  })
  await page.goto(`${baseURL}/?preview=growth`)
  await page.locator('#weekly-daily-budget').waitFor()
  assert.deepEqual(errors, [])
  return page
}

